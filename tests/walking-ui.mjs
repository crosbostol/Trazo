import assert from 'node:assert/strict'
import path from 'node:path'
import { walkingExample } from './walking-checks.mjs'

export async function checkWalkingUi(page,client,today,output) {
  const count=(await (await client.fetch('/api/activities')).json()).length
  await page.getByRole('link',{name:'Importar',exact:true}).click()
  await page.getByLabel('JSON de la actividad').fill(JSON.stringify({date:today,type:'Walking',durationSeconds:911,walking:walkingExample}).slice(0,-1)+',"rawPayload":{"id":9007199254740993,"big":1e400}}')
  await page.getByRole('button',{name:'Validar',exact:true}).click()
  const preview=page.getByRole('region',{name:'Vista previa'})
  const text=await preview.innerText()
  for(const expected of ['Caminata','1,26','15:11','12:04','148','161','2,5']) assert.ok(text.includes(expected),expected)
  await preview.scrollIntoViewIfNeeded()
  await page.screenshot({path:path.join(output,'walking-import-mobile.png'),fullPage:true})
  await page.getByRole('button',{name:'Importar actividad',exact:true}).click()
  assert.equal((await (await client.fetch('/api/activities')).json()).length,count)
  await page.getByRole('button',{name:'Confirmar y guardar',exact:true}).click()
  await page.getByRole('heading',{name:'Tu caminata en detalle',exact:true}).waitFor()
  const importedUrl=page.url()
  const id=importedUrl.split('/').at(-1)
  assert.match((await (await client.fetch('/api/activities/'+id)).json()).rawPayloadJson,/9007199254740993/)
  const metrics=await page.locator('.metric-grid').innerText()
  for(const expected of ['1,26','15:11','12:04','148','1616','163','188']) assert.ok(metrics.replaceAll('.','').includes(expected),expected)
  assert.equal(await page.getByRole('heading',{name:'Vueltas y splits'}).count(),0)
  await page.screenshot({path:path.join(output,'walking-detail-mobile.png'),fullPage:true})
  await page.getByRole('link',{name:'Actividades',exact:true}).click()
  const row=page.locator('tr').filter({has:page.locator('a[href="/activities/'+id+'"]')})
  await row.waitFor()
  for(const expected of ['Caminata','1,26','15:11','12:04','148']) assert.ok((await row.innerText()).includes(expected),expected)
  await page.getByRole('link',{name:'Registrar actividad',exact:true}).click()
  await page.getByRole('combobox',{name:/^Tipo/}).selectOption('Walking')
  await page.getByLabel('Duración · minutos',{exact:true}).fill('15')
  await page.getByLabel('Segundos',{exact:true}).fill('11')
  await page.getByLabel('Distancia (km)',{exact:true}).fill('1.26')
  await page.getByLabel('Ritmo medio (s/km)',{exact:true}).fill('724')
  await page.getByLabel('FC media (bpm)',{exact:true}).fill('148')
  await page.getByText('Más métricas',{exact:true}).click()
  await page.getByLabel('Pasos (pasos)',{exact:true}).fill('1616')
  assert.equal(await page.getByText('Vueltas / splits',{exact:true}).count(),0)
  assert.equal(await page.getByLabel('Potencia media (W)',{exact:true}).count(),0)
  await page.getByRole('button',{name:'Guardar actividad',exact:true}).click()
  await page.getByRole('heading',{name:'Tu caminata en detalle',exact:true}).waitFor()
  assert.ok((await page.locator('.metric-grid').innerText()).replaceAll('.','').includes('1616'))
  await page.getByRole('button',{name:'Eliminar actividad',exact:true}).click()
  await page.getByRole('button',{name:'Sí, eliminar',exact:true}).click()
  await page.getByRole('heading',{name:'Actividades',exact:true}).waitFor()
  await page.goto(importedUrl)
  await page.getByRole('button',{name:'Eliminar actividad',exact:true}).click()
  await page.getByRole('button',{name:'Sí, eliminar',exact:true}).click()
  await page.getByRole('heading',{name:'Actividades',exact:true}).waitFor()
  assert.equal((await (await client.fetch('/api/activities')).json()).length,count)
  console.log('PASS Walking UI: import preview/confirmation, detail, list, manual metrics/steps, no laps/power and confirmed deletion')
}
